// Génère lib/src/generated/contracts.g.dart depuis contracts/ : les contrats
// JSON restent la source de vérité (recopiée telle quelle dans le projet
// pro), et le code les embarque en constantes, ce qui marche partout
// (serveur compilé AOT, Flutter web, tests) sans lire de fichier.
//
// Lancer depuis packages/assistant_contracts : dart run tool/generate.dart
import 'dart:io';

const output = 'lib/src/generated/contracts.g.dart';

void main() {
  File(output).writeAsStringSync(generate(Directory('contracts')));
  stdout.writeln('Wrote $output');
}

String generate(Directory contracts) {
  String read(String path) {
    final text = File('${contracts.path}/$path').readAsStringSync();
    if (text.contains("'''")) {
      throw FormatException("$path contains ''' and cannot be embedded.");
    }
    return "r'''\n$text'''";
  }

  Map<String, String> folder(String path, String extension) {
    final files =
        Directory('${contracts.path}/$path')
            .listSync()
            .whereType<File>()
            .where((f) => f.path.endsWith(extension))
            .map((f) => f.uri.pathSegments.last)
            .toList()
          ..sort();
    return {
      for (final name in files)
        name.substring(0, name.length - extension.length): read('$path/$name'),
    };
  }

  String map(Map<String, String> entries) => [
    '{',
    for (final MapEntry(:key, :value) in entries.entries) "  '$key': $value,",
    '}',
  ].join('\n');

  final schemas = {
    for (final name in [
      'widget-definition',
      'dashboard',
      'data',
      'assistant-input',
      'assistant-events',
    ])
      name: read('$name.schema.json'),
  };

  return '''
// GENERATED by tool/generate.dart from contracts/ — do not edit.
// ignore_for_file: lines_longer_than_80_chars

const sourcesJson = ${read('sources.json')};

const chartRulesJson = ${read('chart-rules.json')};

const aiExposureJson = ${read('ai-exposure.json')};

const systemPrompt = ${read('prompts/system.md')};

const evalsYaml = ${read('evals/requests.yaml')};

/// Outils MCP, par nom.
const toolsJson = <String, String>${map(folder('tools', '.json'))};

/// Schémas JSON des contrats, par nom.
const schemasJson = <String, String>${map(schemas)};

/// Définitions et données d'exemple (aperçus, goldens, tests), par nom.
const fixturesJson = <String, String>${map(folder('fixtures', '.json'))};
''';
}
